"""27. 移除元素

https://leetcode.com/problems/remove-element/

原地去掉所有等于 val 的元素，返回新长度。
题目允许剩余元素打乱顺序，所以测试只检查前 k 个元素的内容。

不变量：
- 使用 k 来标记最终有效数组的索引，从 0 开始，每发现一个符合条件的元素就将元素移到对应位置，并更新 k 的值
- [0, k) 是非 val 的值
- 循环结束以后，[k, len(nums)) 也不一定是 val，这段的数量才等于 val 的总量。循环没走完时，这句还不成立

步骤：
和移动零的思路类似，使用双指针，一个正常遍历数组，一个用来原地标记有效元素的索引。
遍历数组的过程中判断是否是待移除的目标元素，如果是就跳过，不是就把该元素向前移动到数组前面。
这样经过一轮遍历以后，就能把所有非 val 的元素，都按原来的顺序移动到数组前面，最终 k 的值就是新数组的长度。
实际上 [k, len(nums)) 还是有值的，只不过不再需要了。非 val 的元素在遍历过程中移动到了数组前面，尾部只是残留，这段的数量就是数组中 val 的总量。
"""


def remove_element(nums: list, val: int) -> int:
    k = 0
    for i in range(len(nums)):
        if nums[i] != val:
            nums[k] = nums[i]
            k += 1
    return k